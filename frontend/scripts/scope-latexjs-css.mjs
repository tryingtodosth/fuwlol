// LaTeX.js ships its stylesheet with GLOBAL selectors (body, h2, .list …) and hides it
// behind an export map Vite cannot resolve. This writes a copy scoped under `.latex-doc`
// so a compiled LaTeX post gets LaTeX.js's look without restyling the rest of the site.
// Runs from `npm run prepare`; the output is committed too, so a clone builds either way.
import fs from 'node:fs';
import path from 'node:path';

const dist = path.resolve('node_modules/latex.js/dist/css');
const out = path.resolve('src/lib/render/latexjs.scoped.css');
const read = (f) => fs.readFileSync(path.join(dist, f), 'utf8').replace(/@import[^;]*;/g, '');
const src = read('base.css') + '\n' + read('article.css');
const ROOTS = new Set([':root', ':host', 'body', 'html', '.page']);
const scoped = src.replace(/(^|\})([^{}@]+)\{/g, (m, before, selectors) => {
	const list = selectors.split(',').map((s) => s.trim()).filter(Boolean).map((s) => (ROOTS.has(s) ? '.latex-doc' : `.latex-doc ${s}`));
	return `${before}\n${[...new Set(list)].join(', ')} {`;
});
const header = '/* GENERATED by scripts/scope-latexjs-css.mjs from latex.js/dist/css — do not edit. */\n' +
	'.latex-doc { font-family: "Latin Modern Roman", "Computer Modern", "CMU Serif", Georgia, "Times New Roman", serif; }\n';
fs.writeFileSync(out, header + scoped);
console.log(`wrote ${out} (${scoped.length} bytes)`);
