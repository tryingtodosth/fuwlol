# --- the dispatcher ------------------------------------------------------------------------

def _first(query, key: str) -> str:
    """One value for `key`, from a QueryDict, a plain dict, or a dict of lists. Trimmed,
    and short: a slug is at most 120 characters in this schema, and anything longer is
    somebody probing, not somebody sharing."""
    if not query:
        return ''
    value = query.get(key, '')
    if isinstance(value, (list, tuple)):
        value = value[0] if value else ''
    return str(value or '').strip()[:160]


def normalise_path(path: str) -> str:
    """'/wpis/x/' and '//wpis//x' → '/wpis/x'. Collapsing the slashes is not tidiness: the
    path is pasted into the canonical URL, and `https://fuw.lol` + `//example.com/` reads
    as somebody else's host to a human skimming the preview."""
    path = re.sub(r'/{2,}', '/', '/' + (path or '').strip())
    return '/' + path.strip('/')


def preview_for(path: str, query=None) -> Preview | None:
    """The one entry point. `path` is the SPA route a reader would type, with or without
    the trailing slash; `query` is anything with a `.get` (`request.GET` in the view).

    Returns None for everything an anonymous visitor may not see, for a slug that does not
    resolve, and for a path this site does not serve — one value for three refusals,
    because the whole point is that a scraper cannot tell them apart.
    """
    path = normalise_path(path)
    segments = [s for s in path.split('/') if s]

    if not segments:
        return _home()
    if path in STANDING:
        title, description = STANDING[path]
        return Preview(title=title, description=clean_text(description),
                       url=canonical(path), image=absolute(DEFAULT_IMAGE))
    if path == '/losowe':
        title, description = RANDOM_PAGE
        return Preview(title=title, description=clean_text(description),
                       url=canonical(path), image=absolute(DEFAULT_IMAGE), noindex=True)
    if segments[0] in APP_ROUTES:
        return replace(generic_preview(canonical(path)), noindex=True)

    head = segments[0]
    if head == 'wpis' and len(segments) == 2:
        return _post(segments[1])
    if head == 'przegladaj' and len(segments) == 1:
        return _browse(query)
    if head == 'ludzie':
        if len(segments) == 1:
            return _people_index()
        if len(segments) == 2:
            return _person(segments[1])
        # /ludzie/<slug>/{potwierdz,ustawienia} — a person's own forms, reached from a
        # mail rather than shared — and /ludzie/zgoda/podglad, the badge demo.
        if len(segments) == 3 and segments[2] in ('potwierdz', 'ustawienia', 'podglad'):
            return replace(generic_preview(canonical(path)), noindex=True)
        return None
    if head == 'przedmioty':
        if len(segments) == 1:
            return _subjects_index()
        if len(segments) == 2:
            return _subject(segments[1])
        return None
    return None
